def summarize_conditional(
    pair_df: pd.DataFrame,
    model_df: pd.DataFrame,
    cfg: Phase32Config,
) -> Dict[str, Any]:
    valid = valid_pair_rows(pair_df)
    primary = primary_pair_rows(pair_df)
    positive = positive_lift_rows(pair_df)
    primary_positive = primary_positive_lift_rows(pair_df)
    strong = strong_candidate_rows(pair_df, cfg)
    primary_strong = primary_strong_candidate_rows(pair_df, cfg)
    exploratory = exploratory_lift_rows(pair_df, cfg)
    high_eps_zero_lift = high_epsilon_zero_lift_rows(pair_df, cfg)

    summary: Dict[str, Any] = {
        "available": not pair_df.empty,
        "n_rows": int(len(pair_df)),
        "n_valid_rows": int(len(valid)),
        "n_primary_rows": int(len(primary)),
        "n_positive_lift_rows": int(len(positive)),
        "n_primary_positive_lift_rows": int(len(primary_positive)),
        "n_exploratory_lift_rows": int(len(exploratory)),
        "n_strong_candidate_rows": int(len(strong)),
        "n_primary_strong_candidate_rows": int(len(primary_strong)),
        "n_high_epsilon_zero_lift_rows": int(len(high_eps_zero_lift)),
        "thresholds": {
            "conditional_lift_min": float(cfg.conditional_lift_min),
            "strong_eps_min": float(cfg.strong_eps_min),
            "subject_effect_fraction": float(cfg.subject_effect_fraction),
            "eps_saturation_value": _cfg_float(cfg, "eps_saturation_value", 0.80),
        },
        "model_saturation": summarize_model_saturation(model_df, cfg),
        "pair_saturation": summarize_pair_saturation(pair_df, cfg),
        "interpretation": "",
    }

    if valid.empty:
        summary["interpretation"] = "No valid conditional rows were available."
        return summary

    lift = _numeric_series(valid, "conditional_lift")
    eps = _numeric_series(valid, "augmented_eps_test")
    frac = _numeric_series(valid, "fraction_positive_lift")
    bic = _numeric_series(valid, "bic_improvement")
    ll = _numeric_series(valid, "ll_improvement")

    summary.update(
        {
            "max_conditional_lift": float(lift.max()) if len(lift) else 0.0,
            "max_augmented_eps_test": float(eps.max()) if len(eps) else 0.0,
            "max_fraction_positive_lift": float(frac.max()) if len(frac) else 0.0,
            "best_bic_improvement": float(bic.max()) if len(bic) else 0.0,
            "best_ll_improvement": float(ll.max()) if len(ll) else 0.0,
            "primary_rows": _safe_records(primary),
            "positive_lift_rows": _safe_records(positive),
            "primary_positive_lift_rows": _safe_records(primary_positive),
            "exploratory_lift_rows": _safe_records(exploratory),
            "strong_candidate_rows": _safe_records(strong),
            "primary_strong_candidate_rows": _safe_records(primary_strong),
            "high_epsilon_zero_lift_rows": _safe_records(high_eps_zero_lift),
        }
    )

    if len(primary_strong) > 0:
        summary["interpretation"] = (
            "At least one primary strong candidate row exists before final replication review."
        )
    elif len(strong) > 0:
        summary["interpretation"] = (
            "Strong candidate rows exist only outside the primary registered structure."
        )
    elif len(positive) > 0:
        summary["interpretation"] = (
            "Positive conditional lift rows exist, but they remain exploratory because they "
            "do not satisfy all registered criteria simultaneously."
        )
    else:
        summary["interpretation"] = (
            "No positive conditional lift rows were detected."
        )

    return summary


