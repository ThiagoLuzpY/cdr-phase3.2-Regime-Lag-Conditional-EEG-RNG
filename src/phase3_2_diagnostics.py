def run_phase3_2_diagnostics(cfg: Optional[Phase32Config] = None) -> Dict[str, Any]:
    if cfg is None:
        cfg = load_phase3_2_config()

    paths = phase3_2_paths(cfg)
    diagnostics_dir = paths["diagnostics_dir"]
    diagnostics_dir.mkdir(parents=True, exist_ok=True)

    print("\n" + "=" * 78)
    print("CDR Phase III.2 — Diagnostics")
    print("Leakage-safe conditional estimator aware version")
    print("=" * 78)

    runner_report = load_json(paths["runner_report"])
    gates_json = load_json(paths["gates_json"])
    mc_guard = load_json(paths["mc_guard"])
    controls_json = load_json(paths["controls_json"])
    loader_metadata = load_json(paths["loader_metadata"])

    pair_df = load_csv(paths["conditional_pair_scores"])
    model_df = load_csv(paths["conditional_model_scores"])
    control_runs_df = load_csv(paths["control_runs"])
    control_pair_df = load_csv(paths["control_pair_scores"])
    metrics_table_df = load_csv(paths["metrics_table"])
    regime_df = load_csv(paths["regime_inventory"])
    lag_df = load_csv(paths["lag_inventory"])

    print(f"[Diagnostics] conditional pair rows: {len(pair_df)}")
    print(f"[Diagnostics] conditional model rows: {len(model_df)}")
    print(f"[Diagnostics] control run rows: {len(control_runs_df)}")
    print(f"[Diagnostics] control pair rows: {len(control_pair_df)}")
    print(f"[Diagnostics] regime rows: {len(regime_df)}")
    print(f"[Diagnostics] lag rows: {len(lag_df)}")

    conditional_summary = summarize_conditional(pair_df, model_df, cfg)
    control_summary = summarize_control_runs(control_runs_df, cfg)
    controls_json_summary = summarize_controls_json(controls_json)
    gates_summary = summarize_gates(gates_json, metrics_table_df)
    inventory_summary = summarize_regime_and_lag_inventory(regime_df, lag_df)

    final_interpretation = build_final_diagnostic_interpretation(
        conditional_summary=conditional_summary,
        controls_summary=control_summary,
        gates_summary=gates_summary,
    )

    best_rows = best_rows_by_metric(pair_df)
    primary_rows = primary_pair_rows(pair_df)
    positive_rows = positive_lift_rows(pair_df)
    exploratory_rows = exploratory_lift_rows(pair_df, cfg)
    strong_rows = strong_candidate_rows(pair_df, cfg)
    high_eps_zero_lift = high_epsilon_zero_lift_rows(pair_df, cfg)
    control_breakdown = pd.DataFrame(control_summary.get("control_breakdown", []))

    report: Dict[str, Any] = {
        "phase": cfg.phase_name,
        "project_name": cfg.project_name,
        "diagnostics_version": "phase3_2_diagnostics_v2_leakage_safe",
        "source_files": {k: str(v) for k, v in paths.items() if k != "diagnostics_dir"},
        "runner_final_status": runner_report.get("final_status", {}),
        "loader_metadata_summary": {
            "n_subjects_loaded": loader_metadata.get("n_subjects_loaded"),
            "subjects_loaded": loader_metadata.get("subjects_loaded"),
            "total_rows": loader_metadata.get("total_rows"),
            "rng_bit_count": loader_metadata.get("rng_bit_count"),
        },
        "conditional_diagnostics": conditional_summary,
        "control_diagnostics": control_summary,
        "controls_json_summary": controls_json_summary,
        "gates_diagnostics": gates_summary,
        "regime_lag_inventory": inventory_summary,
        "multiple_comparison_guard": mc_guard,
        "final_interpretation": final_interpretation,
    }

    # -----------------------------------------------------
    # Save diagnostic artifacts
    # -----------------------------------------------------
    report_json = diagnostics_dir / "phase3_2_diagnostics_report.json"
    summary_txt = diagnostics_dir / "phase3_2_diagnostics_summary.txt"
    primary_csv = diagnostics_dir / "phase3_2_primary_tests.csv"
    best_csv = diagnostics_dir / "phase3_2_best_rows.csv"
    positive_csv = diagnostics_dir / "phase3_2_positive_lift_rows.csv"
    exploratory_csv = diagnostics_dir / "phase3_2_exploratory_lift_rows.csv"
    strong_csv = diagnostics_dir / "phase3_2_strong_candidate_rows.csv"
    high_eps_csv = diagnostics_dir / "phase3_2_high_epsilon_zero_lift_rows.csv"
    control_breakdown_csv = diagnostics_dir / "phase3_2_control_breakdown.csv"
    control_pair_csv = diagnostics_dir / "phase3_2_control_pair_scores_copy.csv"
    gates_csv = diagnostics_dir / "phase3_2_gates_copy.csv"

    save_json(report_json, report)

    with open(summary_txt, "w", encoding="utf-8") as f:
        f.write(build_diagnostics_summary_text(report))

    primary_rows.to_csv(primary_csv, index=False)
    best_rows.to_csv(best_csv, index=False)
    positive_rows.to_csv(positive_csv, index=False)
    exploratory_rows.to_csv(exploratory_csv, index=False)
    strong_rows.to_csv(strong_csv, index=False)
    high_eps_zero_lift.to_csv(high_eps_csv, index=False)
    control_breakdown.to_csv(control_breakdown_csv, index=False)
    control_pair_df.to_csv(control_pair_csv, index=False)
    metrics_table_df.to_csv(gates_csv, index=False)

    print("\n" + "=" * 78)
    print("Phase III.2 diagnostics completed")
    print("=" * 78)
    print(f"diagnostics report: {report_json}")
    print(f"diagnostics summary: {summary_txt}")
    print(f"primary tests: {primary_csv}")
    print(f"best rows: {best_csv}")
    print(f"positive lift rows: {positive_csv}")
    print(f"exploratory lift rows: {exploratory_csv}")
    print(f"strong candidate rows: {strong_csv}")
    print(f"high epsilon / zero lift rows: {high_eps_csv}")
    print(f"control breakdown: {control_breakdown_csv}")
    print("=" * 78 + "\n")

    return report


