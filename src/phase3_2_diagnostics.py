def summarize_model_saturation(
    model_df: pd.DataFrame,
    cfg: Phase32Config,
) -> Dict[str, Any]:
    if model_df.empty:
        return {
            "available": False,
            "reason": "model_scores_missing",
        }

    eps_saturation_value = _cfg_float(cfg, "eps_saturation_value", 0.80)

    eps_cols = [
        col for col in ["eps_candidate", "eps_calib", "eps_test"]
        if col in model_df.columns
    ]

    if not eps_cols:
        return {
            "available": False,
            "reason": "no_epsilon_columns_available",
        }

    summary: Dict[str, Any] = {
        "available": True,
        "eps_saturation_value": eps_saturation_value,
        "n_model_rows": int(len(model_df)),
        "columns": {},
    }

    for col in eps_cols:
        values = _numeric_series(model_df, col)
        saturated = values >= eps_saturation_value

        summary["columns"][col] = {
            "max": float(values.max()) if len(values) else 0.0,
            "mean": float(values.mean()) if len(values) else 0.0,
            "n_saturated": int(saturated.sum()),
            "saturation_fraction": float(np.mean(saturated.to_numpy(dtype=bool))) if len(saturated) else 0.0,
        }

    if "eps_saturated" in model_df.columns:
        explicit = _as_bool_series(model_df["eps_saturated"])
        summary["explicit_eps_saturated"] = {
            "n_saturated": int(explicit.sum()),
            "saturation_fraction": float(np.mean(explicit.to_numpy(dtype=bool))) if len(explicit) else 0.0,
        }

    max_fraction = max(
        item.get("saturation_fraction", 0.0)
        for item in summary["columns"].values()
    )

    warning_fraction = _cfg_float(cfg, "eps_saturation_warning_fraction", 0.50)

    summary["max_saturation_fraction"] = float(max_fraction)
    summary["warning_fraction"] = float(warning_fraction)
    summary["warning"] = bool(max_fraction >= warning_fraction)
    summary["reason"] = "epsilon_saturation_warning" if summary["warning"] else "ok"

    return summary


def summarize_pair_saturation(
    pair_df: pd.DataFrame,
    cfg: Phase32Config,
) -> Dict[str, Any]:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return {
            "available": False,
            "reason": "no_valid_pair_rows",
        }

    eps_saturation_value = _cfg_float(cfg, "eps_saturation_value", 0.80)
    warning_fraction = _cfg_float(cfg, "eps_saturation_warning_fraction", 0.50)

    baseline_eps = _numeric_series(valid, "baseline_eps_test")
    augmented_eps = _numeric_series(valid, "augmented_eps_test")

    baseline_sat = baseline_eps >= eps_saturation_value
    augmented_sat = augmented_eps >= eps_saturation_value
    either_sat = baseline_sat | augmented_sat
    both_sat = baseline_sat & augmented_sat

    either_fraction = float(np.mean(either_sat.to_numpy(dtype=bool))) if len(either_sat) else 0.0
    both_fraction = float(np.mean(both_sat.to_numpy(dtype=bool))) if len(both_sat) else 0.0

    return {
        "available": True,
        "eps_saturation_value": float(eps_saturation_value),
        "warning_fraction": float(warning_fraction),
        "n_valid_pair_rows": int(len(valid)),
        "max_baseline_eps_test": float(baseline_eps.max()) if len(baseline_eps) else 0.0,
        "max_augmented_eps_test": float(augmented_eps.max()) if len(augmented_eps) else 0.0,
        "n_either_saturated": int(either_sat.sum()),
        "n_both_saturated": int(both_sat.sum()),
        "either_saturation_fraction": either_fraction,
        "both_saturation_fraction": both_fraction,
        "warning": bool(either_fraction >= warning_fraction),
        "reason": "pair_level_epsilon_saturation_warning" if either_fraction >= warning_fraction else "ok",
    }


