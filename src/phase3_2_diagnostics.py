# Final interpretation
# =========================================================

def build_final_diagnostic_interpretation(
    conditional_summary: Mapping[str, Any],
    controls_summary: Mapping[str, Any],
    gates_summary: Mapping[str, Any],
    multichannel_summary: Mapping[str, Any],
    cfg: Phase32Config,
) -> Dict[str, Any]:
    final_status = gates_summary.get("final_status", {})
    status = final_status.get("status", "unknown")

    n_positive = _safe_int(conditional_summary.get("n_positive_lift_rows"))
    n_primary_positive = _safe_int(conditional_summary.get("n_primary_positive_lift_rows"))
    n_strong = _safe_int(conditional_summary.get("n_strong_candidate_rows"))
    n_primary_strong = _safe_int(conditional_summary.get("n_primary_strong_candidate_rows"))

    n_mc_positive = _safe_int(multichannel_summary.get("n_multichannel_positive_lift_rows"))
    n_mc_strong = _safe_int(multichannel_summary.get("n_multichannel_strong_candidate_rows"))

    controls_failed = _safe_int(controls_summary.get("n_failed_control_types")) > 0

    failed_gates = gates_summary.get("failed_gates", [])
    warning_gates = gates_summary.get("warning_gates", [])
    not_eval = gates_summary.get("not_evaluated_gates", [])

    if status == "candidate_signal":
        headline = "Phase III.2 produced a primary candidate signal."
    elif status == "blocked_by_controls":
        headline = "Phase III.2 is blocked by controls."
    elif status == "exploratory_lead_with_saturation_warning":
        headline = "Phase III.2 produced exploratory leads with ε saturation warning."
    elif status == "exploratory_lead_only":
        headline = "Phase III.2 produced exploratory leads only."
    elif status == "conditional_null_result":
        headline = "Phase III.2 produced a clean conditional null result."
    elif status == "pending_controls_exploratory_lead":
        headline = "Phase III.2 has exploratory leads but controls are pending."
    else:
        headline = "Phase III.2 produced a non-confirmatory result."

    scientific_read: List[str] = []

    if n_positive > 0:
        scientific_read.append(
            f"Positive conditional lift rows were detected: {n_positive}. "
            f"Primary positive rows: {n_primary_positive}."
        )
    else:
        scientific_read.append(
            "No positive conditional lift rows were detected."
        )

    if n_mc_positive > 0:
        scientific_read.append(
            f"Phase III.2D multichannel EEG produced exploratory positive lift rows: {n_mc_positive}."
        )
    else:
        scientific_read.append(
            "Phase III.2D multichannel EEG did not produce positive lift rows."
        )

    if n_strong == 0:
        scientific_read.append(
            "No strong candidate rows satisfied lift, epsilon, subject-consistency and BIC criteria simultaneously."
        )
    else:
        scientific_read.append(
            f"Strong candidate rows detected: {n_strong}. Primary strong candidates: {n_primary_strong}."
        )

    if n_mc_strong == 0:
        scientific_read.append(
            "No Phase III.2D multichannel row satisfied all strong-candidate criteria."
        )
    else:
        scientific_read.append(
            f"Phase III.2D multichannel strong candidates detected: {n_mc_strong}."
        )

    if controls_failed:
        scientific_read.append(
            "At least one negative control did not collapse; strong interpretation is blocked."
        )
    else:
        scientific_read.append(
            "Negative controls collapsed under the leakage-safe criteria, including multichannel-aware controls."
        )

    if "F7" in failed_gates:
        scientific_read.append(
            "F7 failed: subject-level consistency was insufficient for a strong claim."
        )

    if "F8" in failed_gates:
        scientific_read.append(
            "F8 failed: the augmented conditional model was not favored by BIC."
        )

    if "F12" in warning_gates:
        scientific_read.append(
            "F12 warning: ε saturation remains present and must be treated as a diagnostic limitation."
        )

    if not_eval:
        scientific_read.append(
            f"Not evaluated in this standalone diagnostic run: {not_eval}."
        )

    scientific_read.append(
        "Phase III.2E remains protocol-only because Sleep-EDF and ANU QRNG were not synchronously co-acquired."
    )

    if status == "exploratory_lead_with_saturation_warning":
        recommendation = (
            "Treat Phase III.2A/B/C/D as an exploratory lead only. Controls passed, including "
            "multichannel-aware controls, but F7/F8 failed and F12 raised an ε saturation warning. "
            "Do not claim EEG-RNG coupling. Document III.2D as an exploratory multichannel enrichment "
            "that increased positive-lift rows but did not satisfy subject-consistency, BIC and saturation "
            "requirements. Keep III.2E as a future synchronized EEG + QRNG protocol."
        )
    elif status == "conditional_null_result":
        recommendation = (
            "Treat Phase III.2 as a clean conditional null result under the current public-data design."
        )
    elif status == "blocked_by_controls":
        recommendation = (
            "Do not proceed to a positive interpretation. Inspect control-level outputs before extending the phase."
        )
    else:
        recommendation = (
            "Treat Phase III.2 as non-confirmatory unless future diagnostics satisfy controls, subject consistency, BIC and saturation criteria."
        )

    return {
        "headline": headline,
        "status": status,
        "scientific_read": scientific_read,
        "recommendation": recommendation,
    }


