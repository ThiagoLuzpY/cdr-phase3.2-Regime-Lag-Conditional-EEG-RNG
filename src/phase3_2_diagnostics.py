def valid_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    if pair_df.empty or "valid" not in pair_df.columns:
        return pd.DataFrame()

    return pair_df[_as_bool_series(pair_df["valid"])].copy()


def primary_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty or "primary" not in valid.columns:
        return pd.DataFrame()

    return valid[_as_bool_series(valid["primary"])].copy()


def positive_lift_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    lift = _numeric_series(valid, "conditional_lift")
    return valid[lift > 0.0].copy()


def primary_positive_lift_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    primary = primary_pair_rows(pair_df)

    if primary.empty:
        return pd.DataFrame()

    lift = _numeric_series(primary, "conditional_lift")
    return primary[lift > 0.0].copy()


def strong_candidate_rows(pair_df: pd.DataFrame, cfg: Phase32Config) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    lift = _numeric_series(valid, "conditional_lift")
    eps = _numeric_series(valid, "augmented_eps_test")
    frac = _numeric_series(valid, "fraction_positive_lift")
    bic = _numeric_series(valid, "bic_improvement")

    strong = valid[
        (lift >= float(cfg.conditional_lift_min))
        & (eps >= float(cfg.strong_eps_min))
        & (frac >= float(cfg.subject_effect_fraction))
        & (bic >= 0.0)
    ].copy()

    return strong


def primary_strong_candidate_rows(pair_df: pd.DataFrame, cfg: Phase32Config) -> pd.DataFrame:
    strong = strong_candidate_rows(pair_df, cfg)

    if strong.empty or "primary" not in strong.columns:
        return pd.DataFrame()

    return strong[_as_bool_series(strong["primary"])].copy()


def exploratory_lift_rows(pair_df: pd.DataFrame, cfg: Phase32Config) -> pd.DataFrame:
    positive = positive_lift_rows(pair_df)

    if positive.empty:
        return pd.DataFrame()

    strong = strong_candidate_rows(pair_df, cfg)

    if strong.empty:
        return positive.copy()

    return positive[~positive.index.isin(set(strong.index.tolist()))].copy()


def high_epsilon_zero_lift_rows(
    pair_df: pd.DataFrame,
    cfg: Phase32Config,
) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    eps_threshold = _cfg_float(cfg, "eps_saturation_value", 0.80)

    eps = _numeric_series(valid, "augmented_eps_test")
    lift = _numeric_series(valid, "conditional_lift")

    return valid[(eps >= eps_threshold) & (lift <= 0.0)].copy()


def best_rows_by_metric(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    metrics = [
        ("conditional_lift", True),
        ("augmented_eps_test", True),
        ("baseline_eps_test", True),
        ("ll_improvement", True),
        ("bic_improvement", True),
        ("aic_improvement", True),
        ("fraction_positive_lift", True),
    ]

    rows: List[Dict[str, Any]] = []

    for metric, descending in metrics:
        if metric not in valid.columns:
            continue

        sorted_df = valid.sort_values(metric, ascending=not descending).reset_index(drop=True)

        if sorted_df.empty:
            continue

        row = sorted_df.iloc[0].to_dict()
        row["selected_by"] = metric
        rows.append(row)

    if not rows:
        return pd.DataFrame()

    best_df = pd.DataFrame(rows)

    preferred_columns = [
        "selected_by",
        "regime",
        "lag_epochs",
        "lag_label",
        "family",
        "baseline_model",
        "augmented_model",
        "primary",
        "valid",
        "baseline_eps_test",
        "augmented_eps_test",
        "conditional_lift",
        "fraction_positive_lift",
        "ll_improvement",
        "bic_improvement",
        "aic_improvement",
        "n_subjects_evaluated",
        "n_subjects_positive_lift",
        "reason",
    ]

    cols = _select_existing_columns(best_df, preferred_columns)
    return best_df[cols].copy()


