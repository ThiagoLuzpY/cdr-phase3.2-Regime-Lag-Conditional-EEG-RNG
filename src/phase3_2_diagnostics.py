def summarize_control_runs(
    control_runs_df: pd.DataFrame,
    cfg: Phase32Config,
) -> Dict[str, Any]:
    if control_runs_df.empty:
        return {
            "available": False,
            "reason": "control_runs_missing",
            "interpretation": "No control run CSV was found.",
        }

    rows: List[Dict[str, Any]] = []

    for control_type, group in control_runs_df.groupby("control_type", sort=True):
        valid = group[_as_bool_series(group["valid"])] if "valid" in group.columns else group.copy()

        if valid.empty:
            rows.append(
                {
                    "control_type": str(control_type),
                    "n_runs": int(len(group)),
                    "n_valid_runs": 0,
                    "median_max_baseline_eps_test": 0.0,
                    "median_max_augmented_eps_test": 0.0,
                    "max_augmented_eps_test": 0.0,
                    "median_max_lift": 0.0,
                    "max_lift": 0.0,
                    "median_max_bic_improvement": 0.0,
                    "max_bic_improvement": 0.0,
                    "median_eps_saturation_fraction": 0.0,
                    "max_eps_saturation_fraction": 0.0,
                    "total_multichannel_pair_rows": 0,
                    "total_multichannel_positive_lift_rows": 0,
                    "total_multichannel_strong_candidate_rows": 0,
                    "fraction_collapsed_overall": 0.0,
                    "passed_estimate": False,
                    "reason": "no_valid_runs",
                }
            )
            continue

        baseline_eps = _numeric_series(valid, "max_baseline_eps_test")
        augmented_eps = _numeric_series(valid, "max_augmented_eps_test")
        max_lift = _numeric_series(valid, "max_conditional_lift")
        max_bic = _numeric_series(valid, "max_bic_improvement")
        sat_frac = _numeric_series(valid, "eps_saturation_fraction")

        if "collapsed_overall" in valid.columns:
            collapsed = _as_bool_series(valid["collapsed_overall"])
        else:
            frac = _numeric_series(valid, "max_fraction_positive_lift")
            n_strong = _numeric_series(valid, "n_strong_candidate_rows")
            collapsed = (
                (max_lift <= float(cfg.control_tol))
                & (max_bic <= 0.0)
                & (frac < float(cfg.subject_effect_fraction))
                & (n_strong.astype(int) == 0)
            )

        fraction_collapsed = float(np.mean(collapsed.to_numpy(dtype=bool))) if len(collapsed) else 0.0
        passed_estimate = fraction_collapsed >= float(cfg.required_control_fraction)

        total_mc_pair = 0
        total_mc_positive = 0
        total_mc_strong = 0

        for col, target in [
            ("n_multichannel_pair_rows", "pair"),
            ("n_multichannel_positive_lift_rows", "positive"),
            ("n_multichannel_strong_candidate_rows", "strong"),
        ]:
            if col not in valid.columns:
                continue

            value = int(pd.to_numeric(valid[col], errors="coerce").fillna(0).sum())

            if target == "pair":
                total_mc_pair = value
            elif target == "positive":
                total_mc_positive = value
            elif target == "strong":
                total_mc_strong = value

        rows.append(
            {
                "control_type": str(control_type),
                "n_runs": int(len(group)),
                "n_valid_runs": int(len(valid)),
                "median_max_baseline_eps_test": float(baseline_eps.median()) if len(baseline_eps) else 0.0,
                "median_max_augmented_eps_test": float(augmented_eps.median()) if len(augmented_eps) else 0.0,
                "mean_max_augmented_eps_test": float(augmented_eps.mean()) if len(augmented_eps) else 0.0,
                "max_augmented_eps_test": float(augmented_eps.max()) if len(augmented_eps) else 0.0,
                "median_max_lift": float(max_lift.median()) if len(max_lift) else 0.0,
                "mean_max_lift": float(max_lift.mean()) if len(max_lift) else 0.0,
                "max_lift": float(max_lift.max()) if len(max_lift) else 0.0,
                "median_max_bic_improvement": float(max_bic.median()) if len(max_bic) else 0.0,
                "max_bic_improvement": float(max_bic.max()) if len(max_bic) else 0.0,
                "median_eps_saturation_fraction": float(sat_frac.median()) if len(sat_frac) else 0.0,
                "max_eps_saturation_fraction": float(sat_frac.max()) if len(sat_frac) else 0.0,
                "total_multichannel_pair_rows": total_mc_pair,
                "total_multichannel_positive_lift_rows": total_mc_positive,
                "total_multichannel_strong_candidate_rows": total_mc_strong,
                "fraction_collapsed_overall": fraction_collapsed,
                "required_control_fraction": float(cfg.required_control_fraction),
                "control_tol": float(cfg.control_tol),
                "passed_estimate": bool(passed_estimate),
                "reason": "ok" if passed_estimate else "control_effect_survived",
            }
        )

    breakdown = pd.DataFrame(rows)
    failed = breakdown[breakdown["passed_estimate"] == False].copy()

    return {
        "available": True,
        "n_control_types": int(len(breakdown)),
        "n_failed_control_types": int(len(failed)),
        "failed_control_types": failed["control_type"].tolist() if not failed.empty else [],
        "control_breakdown": breakdown.to_dict(orient="records"),
        "total_multichannel_pair_rows": int(breakdown["total_multichannel_pair_rows"].sum()) if "total_multichannel_pair_rows" in breakdown.columns else 0,
        "total_multichannel_positive_lift_rows": int(breakdown["total_multichannel_positive_lift_rows"].sum()) if "total_multichannel_positive_lift_rows" in breakdown.columns else 0,
        "total_multichannel_strong_candidate_rows": int(breakdown["total_multichannel_strong_candidate_rows"].sum()) if "total_multichannel_strong_candidate_rows" in breakdown.columns else 0,
        "interpretation": (
            "All control types collapsed under the leakage-safe control criteria, including Phase III.2D multichannel-aware controls."
            if failed.empty
            else "At least one negative control did not collapse under the leakage-safe control criteria."
        ),
    }


