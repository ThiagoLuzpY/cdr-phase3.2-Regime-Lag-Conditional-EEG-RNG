# Gates diagnostics
# =========================================================

def summarize_gates(
    gates_json: Mapping[str, Any],
    metrics_table_df: pd.DataFrame,
) -> Dict[str, Any]:
    if gates_json:
        final_status = gates_json.get("final_status", {})
        gates = gates_json.get("gates", [])
        epsilon_saturation = gates_json.get("epsilon_saturation", {})
    else:
        final_status = {}
        gates = metrics_table_df.to_dict(orient="records") if not metrics_table_df.empty else []
        epsilon_saturation = {}

    passed: List[str] = []
    failed: List[str] = []
    not_evaluated: List[str] = []
    warnings: List[str] = []

    for gate in gates:
        status = str(gate.get("status", "")).upper()
        name = str(gate.get("gate", ""))

        if status == "PASS":
            passed.append(name)
        elif status == "FAIL":
            failed.append(name)
        elif status == "NOT_EVALUATED":
            not_evaluated.append(name)
        elif status == "WARN":
            warnings.append(name)

    return {
        "available": bool(gates),
        "final_status": final_status,
        "passed_gates": passed,
        "failed_gates": failed,
        "not_evaluated_gates": not_evaluated,
        "warning_gates": warnings,
        "gates": gates,
        "epsilon_saturation": epsilon_saturation,
    }


# =========================================================
# Regime / lag diagnostics
# =========================================================

def summarize_regime_and_lag_inventory(
    regime_df: pd.DataFrame,
    lag_df: pd.DataFrame,
) -> Dict[str, Any]:
    summary: Dict[str, Any] = {
        "regime_inventory_available": not regime_df.empty,
        "lag_inventory_available": not lag_df.empty,
    }

    if not regime_df.empty:
        valid_col = _as_bool_series(regime_df["valid"]) if "valid" in regime_df.columns else pd.Series([], dtype=bool)

        summary["regimes"] = {
            "n_regimes": int(len(regime_df)),
            "n_valid_regimes": int(valid_col.sum()) if not valid_col.empty else 0,
            "valid_regimes": regime_df.loc[valid_col, "regime"].astype(str).tolist() if "regime" in regime_df.columns and not valid_col.empty else [],
            "rows": _safe_records(regime_df),
        }

    if not lag_df.empty:
        valid_col = _as_bool_series(lag_df["valid"]) if "valid" in lag_df.columns else pd.Series([], dtype=bool)

        summary["lags"] = {
            "n_lagged_frames": int(len(lag_df)),
            "n_valid_lagged_frames": int(valid_col.sum()) if not valid_col.empty else 0,
            "rows": _safe_records(lag_df),
        }

    return summary


