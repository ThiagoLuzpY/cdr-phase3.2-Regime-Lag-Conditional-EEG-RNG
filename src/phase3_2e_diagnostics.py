def summarize_control_runs(control_runs_df: pd.DataFrame, controls_payload: Mapping[str, Any], cfg: Phase32EConfig) -> Dict[str, Any]:
    if control_runs_df.empty:
        return {
            "available": bool(controls_payload),
            "protocol_only": _is_protocol_only_payload(controls_payload),
            "status": _status_from_payload(controls_payload),
            "n_control_runs": 0,
            "n_valid_control_runs": 0,
            "n_control_types": 0,
            "failed_control_types": _payload_result(controls_payload).get("failed_control_types", []),
            "required_control_types": _payload_summary(controls_payload).get(
                "required_control_types",
                getattr(cfg, "required_control_types", []),
            ),
            "interpretation": (
                "Controls are protocol-only or unavailable because no synchronized "
                "alignment frames exist."
            ),
        }

    rows: List[Dict[str, Any]] = []

    for control_type, group in control_runs_df.groupby("control_type", sort=True):
        valid = group[_as_bool_series(group["valid"])] if "valid" in group.columns else group.copy()

        if valid.empty:
            rows.append(
                {
                    "control_type": str(control_type),
                    "n_runs": int(len(group)),
                    "n_valid_runs": 0,
                    "fraction_collapsed_overall": 0.0,
                    "passed_estimate": False,
                    "reason": "no_valid_runs",
                }
            )
            continue

        if "collapsed_overall" in valid.columns:
            collapsed = _as_bool_series(valid["collapsed_overall"])
        else:
            lift = _numeric_series(valid, "max_conditional_lift")
            bic = _numeric_series(valid, "max_bic_improvement")
            frac = _numeric_series(valid, "max_fraction_positive_lift")
            n_strong = _numeric_series(valid, "n_strong_candidate_rows")
            collapsed = (
                (lift <= float(cfg.control_tol))
                & (bic <= 0.0)
                & (frac < float(cfg.subject_effect_fraction))
                & (n_strong.astype(int) == 0)
            )

        fraction_collapsed = float(np.mean(collapsed.to_numpy(dtype=bool))) if len(collapsed) else 0.0
        passed_estimate = fraction_collapsed >= float(getattr(cfg, "required_control_fraction", 1.0))

        rows.append(
            {
                "control_type": str(control_type),
                "n_runs": int(len(group)),
                "n_valid_runs": int(len(valid)),
                "median_max_augmented_eps_test": float(_numeric_series(valid, "max_augmented_eps_test").median()),
                "max_augmented_eps_test": float(_numeric_series(valid, "max_augmented_eps_test").max()),
                "median_max_lift": float(_numeric_series(valid, "max_conditional_lift").median()),
                "max_lift": float(_numeric_series(valid, "max_conditional_lift").max()),
                "median_max_bic_improvement": float(_numeric_series(valid, "max_bic_improvement").median()),
                "max_bic_improvement": float(_numeric_series(valid, "max_bic_improvement").max()),
                "fraction_collapsed_overall": fraction_collapsed,
                "required_control_fraction": float(getattr(cfg, "required_control_fraction", 1.0)),
                "control_tol": float(getattr(cfg, "control_tol", 0.05)),
                "passed_estimate": bool(passed_estimate),
                "reason": "ok" if passed_estimate else "control_effect_survived",
            }
        )

    breakdown = pd.DataFrame(rows)
    failed = breakdown[breakdown["passed_estimate"] == False].copy()

    return {
        "available": True,
        "protocol_only": _is_protocol_only_payload(controls_payload),
        "status": _status_from_payload(controls_payload),
        "n_control_runs": int(len(control_runs_df)),
        "n_valid_control_runs": int(_as_bool_series(control_runs_df["valid"]).sum()) if "valid" in control_runs_df.columns else int(len(control_runs_df)),
        "n_control_types": int(len(breakdown)),
        "n_failed_control_types": int(len(failed)),
        "failed_control_types": failed["control_type"].tolist() if not failed.empty else [],
        "required_control_types": _payload_summary(controls_payload).get(
            "required_control_types",
            getattr(cfg, "required_control_types", []),
        ),
        "control_breakdown": breakdown.to_dict(orient="records"),
        "interpretation": (
            "All synchronized negative controls collapsed under the official criteria."
            if failed.empty
            else "At least one synchronized negative control did not collapse."
        ),
    }


