def build_final_diagnostic_interpretation(
    protocol_summary: Mapping[str, Any],
    conditional_summary: Mapping[str, Any],
    controls_summary: Mapping[str, Any],
    gates_summary: Mapping[str, Any],
    sensitivity_summary: Mapping[str, Any],
    cfg: Phase32EConfig,
) -> Dict[str, Any]:
    final_status = gates_summary.get("final_status", {})
    status = str(final_status.get("status", gates_summary.get("status", "unknown")))

    protocol_only = bool(
        protocol_summary.get("any_protocol_only_stage", False)
        or conditional_summary.get("protocol_only", False)
        or controls_summary.get("protocol_only", False)
        or gates_summary.get("protocol_only", False)
        or sensitivity_summary.get("protocol_only", False)
    )

    n_positive = _safe_int(conditional_summary.get("n_positive_lift_rows"))
    n_primary_positive = _safe_int(conditional_summary.get("n_primary_positive_lift_rows"))
    n_strong = _safe_int(conditional_summary.get("n_strong_candidate_rows"))
    n_primary_strong = _safe_int(conditional_summary.get("n_primary_strong_candidate_rows"))
    n_mc_positive = _safe_int(conditional_summary.get("n_multichannel_positive_lift_rows"))

    failed_gates = gates_summary.get("failed_gates", [])
    warning_gates = gates_summary.get("warning_gates", [])
    not_eval = gates_summary.get("not_evaluated_gates", [])

    controls_failed = _safe_int(controls_summary.get("n_failed_control_types")) > 0
    empirical_ready = bool(protocol_summary.get("can_proceed_to_empirical_cdr", False))

    if protocol_only or status == getattr(cfg, "status_pending_synchronized_data", "pending_synchronized_data"):
        headline = "Phase III.2E is protocol-ready but empirically pending synchronized EEG–QRNG data."
        recommendation = (
            "Treat Phase III.2E as a completed protocol implementation, not an empirical "
            "result. The next scientific requirement is a real synchronized EEG + QRNG "
            "dataset with valid timestamp alignment. Do not claim EEG–QRNG coupling from "
            "protocol-only outputs."
        )
    elif n_primary_strong > 0 and not controls_failed and "F12" not in warning_gates:
        headline = "Phase III.2E produced a synchronized primary candidate signal."
        recommendation = (
            "Document this as a candidate synchronized EEG–QRNG signal requiring full "
            "diagnostic review, independent replication and protocol audit."
        )
    elif controls_failed:
        headline = "Phase III.2E is blocked by synchronized negative controls."
        recommendation = (
            "Do not claim a positive signal. Inspect control-level outputs and determine "
            "whether the apparent effect survives broken synchronization."
        )
    elif n_positive > 0:
        headline = "Phase III.2E produced exploratory synchronized conditional leads only."
        recommendation = (
            "Document exploratory leads but do not claim empirical CDR unless controls, "
            "F7, F8, F12 and primary-gate criteria are satisfied."
        )
    else:
        headline = "Phase III.2E produced no positive synchronized conditional lift at the current stage."
        recommendation = (
            "Treat this as a synchronized conditional null only if real synchronized data "
            "were available and controls passed. In protocol-only mode, treat it as pending."
        )

    scientific_read: List[str] = []

    if protocol_only:
        scientific_read.append(
            "The current III.2E execution is protocol-only because no real synchronized EEG–QRNG input CSV is available."
        )
    else:
        scientific_read.append(
            "The current III.2E execution used empirical synchronized rows."
        )

    scientific_read.append(
        f"Protocol empirical readiness: {empirical_ready}."
    )

    scientific_read.append(
        f"Positive conditional lift rows: {n_positive}; primary positive rows: {n_primary_positive}."
    )

    scientific_read.append(
        f"Strong candidate rows: {n_strong}; primary strong candidates: {n_primary_strong}."
    )

    scientific_read.append(
        f"Multichannel synchronized positive lift rows: {n_mc_positive}."
    )

    if failed_gates:
        scientific_read.append(f"Failed official gates: {failed_gates}.")

    if warning_gates:
        scientific_read.append(f"Warning gates: {warning_gates}.")

    if not_eval:
        scientific_read.append(f"Not evaluated gates: {not_eval}.")

    if sensitivity_summary.get("available"):
        scientific_read.append(
            "F7/F8/F12 sensitivity diagnostics were generated without changing official gate thresholds."
        )

    scientific_read.append(
        "A positive claim remains prohibited unless synchronized data exist and all required controls/gates support the result."
    )

    return {
        "headline": headline,
        "status": status,
        "protocol_only": bool(protocol_only),
        "can_claim_empirical_cdr": bool(gates_summary.get("can_claim_empirical_cdr", False)),
        "scientific_read": scientific_read,
        "recommendation": recommendation,
    }


