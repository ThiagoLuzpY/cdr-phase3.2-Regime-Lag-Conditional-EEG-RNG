def valid_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    if pair_df.empty or "valid" not in pair_df.columns:
        return pd.DataFrame()

    return pair_df[_as_bool_series(pair_df["valid"])].copy()


def primary_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty or "primary" not in valid.columns:
        return pd.DataFrame()

    return valid[_as_bool_series(valid["primary"])].copy()


def multichannel_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    if "multichannel" in valid.columns:
        return valid[_as_bool_series(valid["multichannel"])].copy()

    mask = pd.Series(np.zeros(len(valid), dtype=bool), index=valid.index)

    for col in ["baseline_model", "augmented_model", "family"]:
        if col not in valid.columns:
            continue

        text = valid[col].astype(str)

        mask |= text.str.contains("MCEEG", case=False, na=False)
        mask |= text.str.contains("MC_EEG", case=False, na=False)
        mask |= text.str.contains("multichannel", case=False, na=False)
        mask |= text.str.startswith("E4")
        mask |= text.str.startswith("E5")
        mask |= text.str.startswith("E6")

    return valid[mask].copy()


def single_channel_pair_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    mc = multichannel_pair_rows(valid)

    if mc.empty:
        return valid.copy()

    return valid[~valid.index.isin(set(mc.index.tolist()))].copy()


def positive_lift_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    return valid[_numeric_series(valid, "conditional_lift") > 0.0].copy()


def primary_positive_lift_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    primary = primary_pair_rows(pair_df)

    if primary.empty:
        return pd.DataFrame()

    return primary[_numeric_series(primary, "conditional_lift") > 0.0].copy()


def multichannel_positive_lift_rows(pair_df: pd.DataFrame) -> pd.DataFrame:
    mc = multichannel_pair_rows(pair_df)

    if mc.empty:
        return pd.DataFrame()

    return mc[_numeric_series(mc, "conditional_lift") > 0.0].copy()


def strong_candidate_rows(pair_df: pd.DataFrame, cfg: Phase32EConfig) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    required = [
        "conditional_lift",
        "augmented_eps_test",
        "fraction_positive_lift",
        "bic_improvement",
    ]

    if any(col not in valid.columns for col in required):
        return pd.DataFrame()

    return valid[
        (_numeric_series(valid, "conditional_lift") >= float(cfg.conditional_lift_min))
        & (_numeric_series(valid, "augmented_eps_test") >= float(cfg.strong_eps_min))
        & (_numeric_series(valid, "fraction_positive_lift") >= float(cfg.subject_effect_fraction))
        & (_numeric_series(valid, "bic_improvement") >= 0.0)
    ].copy()


def primary_strong_candidate_rows(pair_df: pd.DataFrame, cfg: Phase32EConfig) -> pd.DataFrame:
    strong = strong_candidate_rows(pair_df, cfg)

    if strong.empty or "primary" not in strong.columns:
        return pd.DataFrame()

    return strong[_as_bool_series(strong["primary"])].copy()


def exploratory_lift_rows(pair_df: pd.DataFrame, cfg: Phase32EConfig) -> pd.DataFrame:
    positive = positive_lift_rows(pair_df)

    if positive.empty:
        return pd.DataFrame()

    strong = strong_candidate_rows(pair_df, cfg)

    if strong.empty:
        return positive.copy()

    return positive[~positive.index.isin(set(strong.index.tolist()))].copy()


def high_epsilon_zero_lift_rows(pair_df: pd.DataFrame, cfg: Phase32EConfig) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    eps_threshold = float(getattr(cfg, "eps_saturation_value", 0.80))

    eps = _numeric_series(valid, "augmented_eps_test")
    lift = _numeric_series(valid, "conditional_lift")

    return valid[(eps >= eps_threshold) & (lift <= 0.0)].copy()


def best_rows_by_metric(pair_df: pd.DataFrame) -> pd.DataFrame:
    valid = valid_pair_rows(pair_df)

    if valid.empty:
        return pd.DataFrame()

    metrics = [
        ("conditional_lift", True),
        ("augmented_eps_test", True),
        ("baseline_eps_test", True),
        ("ll_improvement", True),
        ("bic_improvement", True),
        ("aic_improvement", True),
        ("fraction_positive_lift", True),
    ]

    rows: List[Dict[str, Any]] = []

    for metric, descending in metrics:
        if metric not in valid.columns:
            continue

        sorted_df = valid.sort_values(metric, ascending=not descending).reset_index(drop=True)

        if sorted_df.empty:
            continue

        row = sorted_df.iloc[0].to_dict()
        row["selected_by"] = metric
        rows.append(row)

    if not rows:
        return pd.DataFrame()

    best_df = pd.DataFrame(rows)

    preferred_columns = [
        "selected_by",
        "window_seconds",
        "lag_windows",
        "lag_seconds",
        "lag_direction",
        "alignment_scope",
        "family",
        "baseline_model",
        "augmented_model",
        "primary",
        "multichannel",
        "valid",
        "baseline_eps_test",
        "augmented_eps_test",
        "conditional_lift",
        "fraction_positive_lift",
        "ll_improvement",
        "bic_improvement",
        "aic_improvement",
        "n_subjects_evaluated",
        "n_subjects_positive_lift",
        "reason",
    ]

    cols = _select_existing_columns(best_df, preferred_columns)

    return best_df[cols].copy()


