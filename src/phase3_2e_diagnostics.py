def summarize_stage_payload(
    name: str,
    payload: Mapping[str, Any],
    expected_status_if_missing: str = "missing",
) -> Dict[str, Any]:
    if not payload:
        return {
            "stage": name,
            "available": False,
            "status": expected_status_if_missing,
            "protocol_only": False,
            "result": {},
            "summary": {},
            "interpretation": "Stage payload is missing.",
        }

    result = _payload_result(payload)
    summary = _payload_summary(payload)

    return {
        "stage": name,
        "available": True,
        "status": _status_from_payload(payload),
        "protocol_only": _is_protocol_only_payload(payload),
        "result": result,
        "summary": summary,
        "interpretation": result.get(
            "interpretation",
            payload.get("interpretation", summary.get("interpretation", "")),
        ),
    }


def summarize_protocol_readiness(
    cfg: Phase32EConfig,
    paths: Mapping[str, Path],
    schema_payload: Mapping[str, Any],
    sync_payload: Mapping[str, Any],
    loader_payload: Mapping[str, Any],
    windows_payload: Mapping[str, Any],
    features_payload: Mapping[str, Any],
    alignment_payload: Mapping[str, Any],
) -> Dict[str, Any]:
    input_file = Path(paths["synchronized_input_csv"])

    schema_status = summarize_stage_payload("schema", schema_payload)
    sync_status = summarize_stage_payload("sync_validation", sync_payload)
    loader_status = summarize_stage_payload("loader", loader_payload)
    windows_status = summarize_stage_payload("windows", windows_payload)
    features_status = summarize_stage_payload("features", features_payload)
    alignment_status = summarize_stage_payload("alignment", alignment_payload)

    stage_statuses = [
        schema_status,
        sync_status,
        loader_status,
        windows_status,
        features_status,
        alignment_status,
    ]

    any_protocol_only = any(item.get("protocol_only", False) for item in stage_statuses)

    empirical_ready_flags = [
        bool(schema_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
        bool(sync_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
        bool(loader_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
        bool(windows_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
        bool(features_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
        bool(alignment_status.get("result", {}).get("can_proceed_to_empirical_cdr", False)),
    ]

    can_empirical = bool(all(empirical_ready_flags)) if empirical_ready_flags else False

    if not input_file.exists():
        status = getattr(cfg, "status_pending_synchronized_data", "pending_synchronized_data")
        interpretation = (
            "No synchronized EEG–QRNG input CSV exists. Phase III.2E is valid as "
            "a protocol-only implementation, but empirical CDR is blocked."
        )
    elif can_empirical:
        status = "empirical_sync_ready"
        interpretation = (
            "Synchronized EEG–QRNG input exists and upstream stages report empirical readiness."
        )
    else:
        status = "sync_pipeline_not_empirically_ready"
        interpretation = (
            "A synchronized input path may exist, but one or more upstream stages do not "
            "report empirical readiness."
        )

    return {
        "status": status,
        "synchronized_input": _file_status(input_file),
        "allow_protocol_only_without_data": bool(getattr(cfg, "allow_protocol_only_without_data", True)),
        "require_real_synchronized_data_for_claim": bool(getattr(cfg, "require_real_synchronized_data_for_claim", True)),
        "any_protocol_only_stage": bool(any_protocol_only),
        "can_proceed_to_empirical_cdr": bool(can_empirical),
        "stages": stage_statuses,
        "interpretation": interpretation,
    }


def summarize_loader_window_feature_alignment_tables(
    loaded_df: pd.DataFrame,
    windows_df: pd.DataFrame,
    features_df: pd.DataFrame,
    alignment_inventory_df: pd.DataFrame,
) -> Dict[str, Any]:
    out: Dict[str, Any] = {
        "loaded_windows_rows": int(len(loaded_df)),
        "windows_rows": int(len(windows_df)),
        "features_rows": int(len(features_df)),
        "alignment_inventory_rows": int(len(alignment_inventory_df)),
    }

    for name, df in [
        ("loaded", loaded_df),
        ("windows", windows_df),
        ("features", features_df),
        ("alignment_inventory", alignment_inventory_df),
    ]:
        if df.empty:
            out[f"{name}_subjects"] = 0
            out[f"{name}_sessions"] = 0
            continue

        out[f"{name}_subjects"] = (
            int(df["subject_id"].nunique())
            if "subject_id" in df.columns
            else 0
        )

        out[f"{name}_sessions"] = (
            int(df[["subject_id", "session_id"]].drop_duplicates().shape[0])
            if {"subject_id", "session_id"}.issubset(df.columns)
            else 0
        )

    if not alignment_inventory_df.empty:
        for col in [
            "n_valid_alignment_rows",
            "n_valid_primary_alignment_rows",
            "n_valid_conditional_rows",
            "n_valid_mc_conditional_rows",
        ]:
            if col in alignment_inventory_df.columns:
                out[f"alignment_total_{col}"] = int(
                    pd.to_numeric(alignment_inventory_df[col], errors="coerce").fillna(0).sum()
                )

        if "alignment_scope" in alignment_inventory_df.columns:
            out["alignment_scope_counts"] = (
                alignment_inventory_df["alignment_scope"]
                .fillna("")
                .astype(str)
                .value_counts()
                .to_dict()
            )

        if "lag_direction" in alignment_inventory_df.columns:
            out["lag_direction_counts"] = (
                alignment_inventory_df["lag_direction"]
                .fillna("")
                .astype(str)
                .value_counts()
                .to_dict()
            )

    return out


