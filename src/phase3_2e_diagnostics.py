def summarize_gates(gates_payload: Mapping[str, Any], metrics_table_df: pd.DataFrame) -> Dict[str, Any]:
    if gates_payload:
        final_status = gates_payload.get("final_status", {})
        gates = gates_payload.get("gates", [])
        epsilon_saturation = gates_payload.get("epsilon_saturation", {})
    else:
        final_status = {}
        gates = metrics_table_df.to_dict(orient="records") if not metrics_table_df.empty else []
        epsilon_saturation = {}

    passed: List[str] = []
    failed: List[str] = []
    not_evaluated: List[str] = []
    warnings: List[str] = []

    for gate in gates:
        status = str(gate.get("status", "")).upper()
        gate_id = str(gate.get("gate", ""))

        if status == "PASS":
            passed.append(gate_id)
        elif status == "FAIL":
            failed.append(gate_id)
        elif status == "NOT_EVALUATED":
            not_evaluated.append(gate_id)
        elif status == "WARN":
            warnings.append(gate_id)

    return {
        "available": bool(gates),
        "final_status": final_status,
        "status": final_status.get("status", gates_payload.get("status") if gates_payload else "missing"),
        "protocol_only": bool(final_status.get("protocol_only", False)),
        "can_claim_empirical_cdr": bool(final_status.get("can_claim_empirical_cdr", False)),
        "passed_gates": passed,
        "failed_gates": failed,
        "not_evaluated_gates": not_evaluated,
        "warning_gates": warnings,
        "gates": gates,
        "epsilon_saturation": epsilon_saturation,
    }


